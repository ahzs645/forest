/**
 * Whether an act belongs in front of this role at all: it has to name the
 * role, and its phase has to be one the role actually works in.
 */
export function actFitsRole(act, roleId) {
  if (!act || act.retired) return false;
  if (!Array.isArray(act.roles) || !act.roles.includes(roleId)) return false;
  const phase = act.phase || "any";
  if (phase === "any") return true;
  return (ROLE_PHASES[roleId] || []).includes(phase);
}


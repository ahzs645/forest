/** Proposer labels, capitalized for the start of a sentence. */
export function capitalizeProposer(proposer) {
  const text = String(proposer || "someone on the job").trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/**
 * The caught band as one paragraph, naming the institution.
 * @param {Object} act
 * @param {number} [variant] 0 or 1; picks the template
 */
export function buildCaughtNarrative(act, variant = 0) {
  const by = act?.catch?.by;
  const how = String(act?.catch?.how || "It does not hold.").trim();
  const templates = CAUGHT_TEMPLATES[by];
  if (!templates) {
    return `${how} The file lands on a desk that asks questions, and your name is on every page of it.`;
  }
  const template = templates[Math.abs(Math.floor(variant)) % templates.length];
  return template(how);
}

